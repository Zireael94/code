static void demo_hello(void) { // 案例一：最小程序和格式化输出
    ui_example("Hello, C! 与 printf 格式化"); // 显示案例标题
    printf("Hello, C!\n"); // 最简单的输出语句，\n 表示换行
    printf("整数=%d，浮点数=%.2f，字符=%c，字符串=%s\n", 42, 3.14, 'A', "C语言"); // 一次输出四种常见类型
    printf("对齐示例：|%5d|%-5d|%05d|\n", 42, 42, 42); // 演示右对齐、左对齐和补零
    printf("转义示例：第一行\n第二行\t制表位\\反斜杠\"双引号\"\n"); // 演示换行、制表、反斜杠和引号
    puts("puts 会自动在末尾换行，适合输出不需要格式控制的整行文字。"); // 对比 puts 与 printf 的用法
} // demo_hello 函数结束

static void demo_profile(void) { // 案例二：读取文本和整数，生成个人名片
    char name[64] = {0}; // 保存姓名，初始化为空字符串更安全
    char city[64] = {0}; // 保存城市，长度足以容纳常见输入
    int age = 0; // 保存年龄
    int months = 0; // 保存换算后的月数
    ui_example("输入输出：生成一张个人名片"); // 显示案例标题
    if (!ui_read_text("请输入你的名字：", name, sizeof(name))) { // 读取一行非空文本
        puts("  已取消输入。"); // 输入结束时给出提示
        return; // 结束当前案例
    } // 姓名输入结束
    age = ui_read_int("请输入年龄（1-120）：", 1, 120); // 读取并校验年龄范围
    if (age < 1) { // 小于 1 表示输入结束或取消
        puts("  已取消输入。"); // 告知用户
        return; // 结束当前案例
    } // 年龄检查结束
    if (!ui_read_text("请输入所在城市：", city, sizeof(city))) { // 读取城市名称
        puts("  已取消输入。"); // 输入结束时提示
        return; // 结束当前案例
    } // 城市输入结束
    months = age * 12; // 用整数乘法换算成月数
    puts("\n  ── 个人名片 ──"); // 输出名片标题
    printf("  姓名：%s\n", name); // 输出姓名
    printf("  城市：%s\n", city); // 输出城市
    printf("  年龄：%d 岁（约 %d 个月）\n", age, months); // 同时输出年龄和月数
    puts("  观察：fgets 能读入带空格的整行文字，scanf 遇到空格会停下。"); // 强调安全输入方式
} // demo_profile 函数结束

static void demo_rectangle(void) { // 案例三：矩形面积与周长计算器
    double width = 0.0; // 保存用户输入的宽度
    double height = 0.0; // 保存用户输入的高度
    double area = 0.0; // 保存计算结果：面积
    double perimeter = 0.0; // 保存计算结果：周长
    ui_example("计算矩形面积和周长"); // 显示案例标题
    width = ui_read_double("请输入宽度（0.1-10000）：", 0.1, 10000.0); // 读取宽度并限制正数范围
    if (isnan(width)) { // NaN 表示输入流结束
        puts("  已取消输入。"); // 友好提示
        return; // 结束案例
    } // 宽度检查结束
    height = ui_read_double("请输入高度（0.1-10000）：", 0.1, 10000.0); // 读取高度并校验范围
    if (isnan(height)) { // 检查是否取消
        puts("  已取消输入。"); // 提示取消
        return; // 结束案例
    } // 高度检查结束
    area = width * height; // 面积公式：宽乘高
    perimeter = 2.0 * (width + height); // 周长公式：两倍的长加宽
    printf("\n  宽度：%.2f\n", width); // 保留两位小数输出宽度
    printf("  高度：%.2f\n", height); // 保留两位小数输出高度
    printf("  面积：%.2f 平方单位\n", area); // 输出面积
    printf("  周长：%.2f 单位\n", perimeter); // 输出周长
    puts("  思考：如果输入负数或 0，程序该如何提示？输入校验正是健壮程序的第一步。"); // 引出边界情况
} // demo_rectangle 函数结束

